// Keyed by lowercased Contentful skill name; skills without a brand icon render text only
const ICONS: Record<string, SimpleIcon> = {
  "html/css": siHtml5,
  javascript: siJavascript,
  react: siReact,
  redux: siRedux,
  typescript: siTypescript,
  contentful: siContentful,
  sanity: siSanity,
  "gatsby.js": siGatsby,
  "next.js": siNextdotjs,
  graphql: siGraphql,
  drupal: siDrupal,
  sketch: siSketch,
  bootstrap: siBootstrap,
  figma: siFigma,
  miro: siMiro,
  storybook: siStorybook,
  bigcommerce: siBigcommerce,
  "algolia search": siAlgolia,
  "styled-components": siStyledcomponents,
  "tailwind css": siTailwindcss,
};

export const skillIcon = (skill: string): SimpleIcon | undefined => ICONS[skill.trim().toLowerCase()];
